#!/usr/bin/env python3
"""Generate every harness variant of the Palanor skill from the one source.

    python skills/palanor/tools/build.py          # write dist/
    python skills/palanor/tools/build.py --check  # fail if dist/ differs from what the source generates

Source (edit these):  source/skill.json, source/SKILL.body.md, source/references/*.md, source/flows.json,
                      tools/tools.lock.json (refresh with tools/refresh_lock.py)
Output (never edit):  dist/<variant>/palanor/...  and any extra files a variant declares.
"""

from __future__ import annotations

import argparse
import difflib
import json
import re
import sys
from pathlib import Path
from typing import Any

sys.path.insert(0, str(Path(__file__).resolve().parent))
from skilllib import DIST, SOURCE, load_flows, load_lock, load_source  # noqa: E402

GENERATED = "Generated by skills/palanor/tools/build.py from skills/palanor/source. Do not edit by hand."


# ---------------------------------------------------------------- frontmatter

PLAIN_OK = re.compile(r"[A-Za-z0-9][A-Za-z0-9 ,.()'/+_-]*[A-Za-z0-9.)]")
YAML_WORDS = {"yes", "no", "true", "false", "on", "off", "null", "~"}


def yaml_str(s: str) -> str:
    """A plain YAML scalar when it is unambiguous, else double-quoted.

    Plain where possible because some harnesses fall back to "key: value" line splitting when their YAML parse
    fails, and that fallback keeps quotes (a quoted name then fails to match its folder).
    """
    if PLAIN_OK.fullmatch(s) and s.lower() not in YAML_WORDS and not re.fullmatch(r"[0-9.]+", s):
        return s
    return json.dumps(s, ensure_ascii=False)


def frontmatter(fields: list[tuple[str, Any]]) -> str:
    """Block-style YAML only: strictyaml (the reference validator) rejects flow style.

    Values: str -> quoted scalar; dict -> nested block map (one level of nesting per dict); list[str] -> block list.
    A raw JSON line can be forced with ("key", {"__raw__": "..."}) for harnesses that read single-line JSON.
    """
    lines = ["---"]

    def emit(key: str, value: Any, indent: int) -> None:
        pad = "  " * indent
        if isinstance(value, dict) and "__raw__" in value:
            lines.append(f"{pad}{key}: {value['__raw__']}")
        elif isinstance(value, dict):
            lines.append(f"{pad}{key}:")
            for k, v in value.items():
                emit(k, v, indent + 1)
        elif isinstance(value, list):
            lines.append(f"{pad}{key}:")
            for item in value:
                lines.append(f"{pad}  - {yaml_str(str(item))}")
        else:
            lines.append(f"{pad}{key}: {yaml_str(str(value))}")

    for k, v in fields:
        emit(k, v, 0)
    lines.append("---")
    return "\n".join(lines) + "\n"


# ---------------------------------------------------------------- references

def tools_reference(src: dict[str, Any], lock: dict[str, dict[str, Any]]) -> str:
    taught: list[str] = src["tools_taught"]
    out = [
        "# Palanor MCP tools: arguments",
        "",
        f"<!-- {GENERATED} -->",
        "",
        "The tools this skill uses, with every argument as the server declares it "
        f"(tools/list on {src['server']}, captured {read_lock_date()}). The server's own list is the authority: if a "
        "call is refused for an argument, read the tool's schema from your client.",
        "",
    ]
    for name in taught:
        t = lock[name]
        out += [f"## {name}", "", t["description"].strip(), ""]
        props = (t.get("inputSchema") or {}).get("properties") or {}
        req = set((t.get("inputSchema") or {}).get("required") or [])
        if not props:
            out += ["No arguments.", ""]
            continue
        out += ["| Argument | Type | Required | Notes |", "|---|---|---|---|"]
        for arg, spec in props.items():
            typ = spec.get("type", "")
            if typ == "array" and isinstance(spec.get("items"), dict):
                typ = f"array of {spec['items'].get('type', 'value')}"
            notes = (spec.get("description") or "").replace("|", "\\|").replace("\n", " ")
            if "enum" in spec:
                notes += " One of: " + ", ".join(f"`{e}`" for e in spec["enum"]) + "."
            if typ.startswith("array of object"):
                sub = spec["items"].get("properties") or {}
                notes += " Each item: " + "; ".join(
                    f"`{k}`" + (" (" + ", ".join(f"`{e}`" for e in v["enum"]) + ")" if "enum" in v else "") for k, v in sub.items()
                ) + "."
            out.append(f"| `{arg}` | {typ} | {'yes' if arg in req else 'no'} | {notes.strip()} |")
        out.append("")
    others = [n for n in lock if n not in taught]
    out += [
        "## The server's other tools",
        "",
        "Not covered by this skill's workflows, but on the same server and the same key. Read each tool's description "
        "before calling it; tools marked Pro or Enterprise refuse a Free key.",
        "",
    ]
    for n in others:
        first = lock[n]["description"].strip().split(". ")[0].rstrip(".")
        gated = " (Pro or Enterprise)" if "Requires a Pro" in lock[n]["description"] else (
            " (Enterprise)" if "Requires an Enterprise" in lock[n]["description"] else "")
        out.append(f"- `{n}`{gated}: {first}.")
    out.append("")
    return "\n".join(out)


def read_lock_date() -> str:
    lock_path = Path(__file__).resolve().parent / "tools.lock.json"
    return str(json.loads(lock_path.read_text(encoding="utf-8")).get("captured", ""))


def render_call(call: str, args: dict[str, Any]) -> str:
    parts = []
    for k, v in args.items():
        if isinstance(v, str) and v.startswith("$"):
            parts.append(f'{k}="<{v[1:].split(".", 1)[-1]} from step {int(v[1:].split(".")[0]) + 1}>"')
        else:
            parts.append(f"{k}={json.dumps(v, ensure_ascii=False)}")
    return f"{call}({', '.join(parts)})"


def examples_reference(flows: list[dict[str, Any]]) -> str:
    out = [
        "# Worked examples",
        "",
        f"<!-- {GENERATED} -->",
        "",
        "Each example is run against the live server by `skills/palanor/tools/flows.py`, so every call below works as "
        "written. The answers show the shape to aim for; their numbers were read on 2026-11-18 and will have moved.",
        "",
    ]
    for i, f in enumerate(flows, 1):
        out += [f"## {i}. \"{f['question']}\"", "", "Calls:", ""]
        for j, s in enumerate(f["steps"], 1):
            line = f"{j}. `{render_call(s['call'], s['args'])}`"
            if "poll" in s:
                line += f" (repeat every {s['poll']['every_s']} s until `{s['poll']['until']}` is `\"{s['poll']['equals']}\"`)"
            out.append(line)
        out += ["", f"Look at: {f['look_at']}", "", "Answer:", ""]
        out += ["> " + ln if ln else ">" for ln in f["answer"].split("\n")]
        out.append("")
    return "\n".join(out)


# ---------------------------------------------------------------- variants

def render_setup(variant: dict[str, Any], src: dict[str, Any]) -> str:
    return "\n".join(variant["setup"]).replace("{server}", src["server"]).replace("{keys_url}", src["keys_url"])


def skill_md(variant: dict[str, Any], src: dict[str, Any], body: str) -> str:
    fields: list[tuple[str, Any]] = [("name", src["name"]), ("description", variant.get("description", src["description"]))]
    for k in variant.get("frontmatter_order", ["license", "compatibility", "metadata"]):
        if k == "license":
            fields.append(("license", src["license"]))
        elif k == "compatibility":
            fields.append(("compatibility", src["compatibility"]))
        elif k == "metadata":
            meta = dict(src["metadata"])
            meta.update(variant.get("metadata", {}))
            fields.append(("metadata", meta))
        elif k in variant.get("extra_fields", {}):
            fields.append((k, variant["extra_fields"][k]))
    text = frontmatter(fields) + "\n" + f"<!-- {GENERATED} -->\n\n" + body.replace("<!--SETUP-->", render_setup(variant, src))
    return text.rstrip() + "\n"


def generate() -> dict[Path, str]:
    """Every file under dist/ (and declared extras), path -> content."""
    src = load_source()
    lock = load_lock()
    flows = load_flows()
    body = (SOURCE / "SKILL.body.md").read_text(encoding="utf-8")
    refs = {p.name: p.read_text(encoding="utf-8") for p in sorted((SOURCE / "references").glob("*.md"))}
    refs["tools.md"] = tools_reference(src, lock)
    refs["examples.md"] = examples_reference(flows)
    files: dict[Path, str] = {}
    for vkey, variant in src["variants"].items():
        base = DIST / vkey / src["name"]
        files[base / "SKILL.md"] = skill_md(variant, src, body)
        for name, text in refs.items():
            files[base / "references" / name] = text if text.endswith("\n") else text + "\n"
        files[base / "LICENSE"] = (SOURCE / "LICENSE").read_text(encoding="utf-8")
        for rel, content in variant.get("extra_files", {}).items():
            text = "\n".join(content) if isinstance(content, list) else content
            text = text.replace("{server}", src["server"]).replace("{keys_url}", src["keys_url"]).replace("{version}", src["metadata"]["version"])
            files[DIST / vkey / rel] = text.rstrip() + "\n"
    return files


def existing() -> dict[Path, str]:
    return {p: p.read_text(encoding="utf-8") for p in DIST.rglob("*") if p.is_file()} if DIST.exists() else {}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true", help="fail if dist/ is not what the source generates")
    a = ap.parse_args()
    want = generate()
    have = existing()
    if a.check:
        problems = []
        for p in sorted(set(want) | set(have)):
            rel = p.relative_to(DIST.parent)
            if p not in have:
                problems.append(f"missing: {rel}")
            elif p not in want:
                problems.append(f"not generated by the source (delete it or add it to the source): {rel}")
            elif have[p] != want[p]:
                diff = "".join(list(difflib.unified_diff(want[p].splitlines(True), have[p].splitlines(True), "generated", "on disk"))[:40])
                problems.append(f"drifted: {rel}\n{diff}")
        if problems:
            print("Variants have drifted from the source. Run: python skills/palanor/tools/build.py\n")
            print("\n".join(problems))
            return 1
        print(f"drift check: {len(want)} generated files match the source")
        return 0
    for p in have:
        if p not in want:
            p.unlink()
    for p, text in want.items():
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(text, encoding="utf-8")
    print(f"wrote {len(want)} files under {DIST.relative_to(DIST.parent.parent.parent)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
